/**
 * Writes `index.ts`: one static import per bundle file, so esbuild inlines every
 * bundle into the API's single-file build (reading this folder from disk at
 * runtime would fail in production).
 *
 *   pnpm --filter @workspace/template-bundles run generate
 *
 * Run it after adding, removing or editing any bundle file; a test fails while
 * the committed index is out of date.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** Folder and file names a bundle may use: lower-case slugs and camelCase kinds. */
const LOOK_SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const KIND = /^[a-z][A-Za-z0-9]*$/;

/** The bundles in `dir`, sorted by look then kind, with each kind file's hash. */
export function readBundles(dir = HERE) {
  const looks = readdirSync(dir)
    .filter((name) => statSync(path.join(dir, name)).isDirectory())
    .filter((name) => name !== "node_modules" && name !== "dist")
    .sort();
  return looks.map((slug) => {
    if (!LOOK_SLUG.test(slug)) throw new Error(`template-bundles: bad look folder name "${slug}"`);
    const files = readdirSync(path.join(dir, slug)).filter((f) => f.endsWith(".json"));
    if (!files.includes("look.json")) throw new Error(`template-bundles: ${slug}/look.json is missing`);
    const kinds = files
      .filter((f) => f !== "look.json")
      .map((f) => f.slice(0, -".json".length))
      .sort();
    for (const kind of kinds) {
      if (!KIND.test(kind)) throw new Error(`template-bundles: bad kind file "${slug}/${kind}.json"`);
    }
    return {
      slug,
      kinds: kinds.map((kind) => ({
        kind,
        hash: createHash("sha256")
          .update(readFileSync(path.join(dir, slug, `${kind}.json`)))
          .digest("hex"),
      })),
    };
  });
}

/** The text of `index.ts` for `dir`. */
export function renderIndex(dir = HERE) {
  const bundles = readBundles(dir);
  const imports = [`import type { TemplateBundle } from "./types";`];
  const entries = bundles.map((b, i) => {
    imports.push(`import look${i} from "./${b.slug}/look.json";`);
    const templates = b.kinds.map((k, j) => {
      imports.push(`import look${i}_${j} from "./${b.slug}/${k.kind}.json";`);
      return `      { kind: ${JSON.stringify(k.kind)}, hash: ${JSON.stringify(k.hash)}, file: look${i}_${j} },`;
    });
    return [
      `  {`,
      `    slug: ${JSON.stringify(b.slug)},`,
      `    look: look${i},`,
      templates.length ? `    templates: [\n${templates.join("\n")}\n    ],` : `    templates: [],`,
      `  },`,
    ].join("\n");
  });
  return [
    `// GENERATED by generate-index.mjs from the bundle folders. Do not edit:`,
    `// run \`pnpm --filter @workspace/template-bundles run generate\`.`,
    ...imports,
    ``,
    `export type * from "./types";`,
    ``,
    entries.length
      ? `export const TEMPLATE_BUNDLES: TemplateBundle[] = [\n${entries.join("\n")}\n];`
      : `export const TEMPLATE_BUNDLES: TemplateBundle[] = [];`,
    ``,
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(HERE, "index.ts"), renderIndex());
  console.log("template-bundles: index.ts written");
}
